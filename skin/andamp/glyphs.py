# --- seven-segment digits, 7x11, drawn at (1, 1) inside the 9x13 cell --------
# Segment geometry: bars are 2px thick with 1px chamfered tips.
_SEGMENTS = {
    "A": [(x, 0) for x in range(2, 5)] + [(x, 1) for x in range(1, 6)],
    "F": [(1, y) for y in range(1, 6)] + [(0, y) for y in range(2, 6)],
    "B": [(5, y) for y in range(1, 6)] + [(6, y) for y in range(2, 6)],
    "G": [(x, 5) for x in range(1, 6)] + [(x, 6) for x in range(1, 6)],
    "E": [(1, y) for y in range(6, 11)] + [(0, y) for y in range(6, 10)],
    "C": [(5, y) for y in range(6, 11)] + [(6, y) for y in range(6, 10)],
    "D": [(x, 9) for x in range(1, 6)] + [(x, 10) for x in range(2, 5)],
}

_DIGIT_SEGMENTS = {
    "0": "ABCDEF", "1": "BC",    "2": "ABGED", "3": "ABGCD", "4": "FGBC",
    "5": "AFGCD", "6": "AFGECD", "7": "ABC",   "8": "ABCDEFG", "9": "ABCDFG",
}


def _digit_rows(d: str):
    on = set()
    for seg in _DIGIT_SEGMENTS[d]:
        on.update(_SEGMENTS[seg])
    return ["".join("#" if (x, y) in on else "." for x in range(7)) for y in range(11)]


DIGITS = {d: _digit_rows(d) for d in _DIGIT_SEGMENTS}
DIGIT_ORIGIN = (1, 1)          # glyph offset inside the 9x13 cell
DIGIT_CELL = (9, 13)

# --- GEN.BMP titlebar caps: 7px tall, variable width -------------------------


def _trim(rows):
    width = max((i + 1 for r in rows for i, ch in enumerate(r) if ch == "#"), default=1)
    return [r[:width] for r in rows]


GEN_FONT = {
    chr(c): ["." * len(_trim(FONT_5x6[chr(c + 32)])[0])]
    + _trim(FONT_5x6[chr(c + 32)])[:5]
    + ["." * len(_trim(FONT_5x6[chr(c + 32)])[0])]
    for c in range(ord("A"), ord("Z") + 1)
}


def measure(text: str) -> int:
    return len(text) * 5


